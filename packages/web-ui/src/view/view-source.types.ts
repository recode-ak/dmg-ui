/**
 * Источник вида: текущее значение и подписка на смену. `subscribe` зовёт
 * слушателя сразу текущим значением, затем на каждое новое; отписка
 * идемпотентна. Значение неизменяемо: смена — новый объект (D-UI-70).
 */
export type ViewSource<T> = {
  get(): T;
  subscribe(listener: (value: T) => void): () => void;
};
