/**
 * Предел длины URL страницы, знаков: общий безопасный предел браузеров и
 * прокси. Длиннее разбор отказывает до любой работы, свой кодек не строит.
 */
export const PAGE_URL_LIMIT = 2048;

/** Имя параметра экрана, модуля и экрана в пути: буква, затем буквы и цифры. */
export const PAGE_URL_NAME = /^[A-Za-z][A-Za-z0-9]*$/;

/** Неизменяемый сегмент шаблона пути маршрута. */
export const PAGE_URL_FIXED = /^[a-z0-9-]+$/;

/**
 * Целое в URL: без ведущих нулей, без `-0`, не больше 16 цифр. Проверка
 * шаблоном до `Number`: тот принимает пробелы, `0x10`, `1e3` и пустую строку.
 */
export const PAGE_URL_INTEGER = /^(?:0|-?[1-9][0-9]{0,15})$/;

/** URL целиком: печатный ASCII без пробела; не-ASCII приходит закодированным. */
export const PAGE_URL_ASCII = /^[\x21-\x7E]*$/;

/** Управляющий знак после декодирования (`%00`, `%0A`, …) — отказ разбора. */
export const PAGE_URL_CONTROL = /\p{Cc}/u;
