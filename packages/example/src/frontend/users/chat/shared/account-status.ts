/** Строка состояния учётной записи: общий кирпич канала `chat` модуля `users`. */
export const AccountStatus = {
  /** «Учётная запись активна» или «Учётная запись не активна». */
  line(active: boolean): string {
    return active ? 'Учётная запись активна' : 'Учётная запись не активна';
  },
} as const;
