/** Зона проверки импортов: файлы по префиксу пути и спецификаторы, которые в них запрещены. */
export type ImportZone = {
  /** Префиксы путей файлов зоны; сегмент `*` — любой один сегмент пути. */
  include: string[];
  /** Суффиксы путей, исключённые из зоны (например `.test.ts`). */
  exclude: string[];
  /** Суффиксы путей файлов зоны (например `-code.ts`); без поля — любые файлы под `include`. */
  suffixes?: string[];
  /** Префиксы путей каталогов, вынесенных из зоны (у них своя зона со своим списком). */
  excludeDirs?: string[];
  /** Запрещённые спецификаторы: точные или с `*` на конце (префикс). */
  forbidden: string[];
  /** Белый список (формат как у `forbidden`): если задан, любой не относительный спецификатор вне списка — нарушение. */
  allowed?: string[];
  /** Префиксы путей от корня репо (сегмент `*` — любой один сегмент): относительный импорт, разрешающийся внутрь, — нарушение. */
  forbiddenPaths?: string[];
  /**
   * Белый список путей (префиксы от корня репо): если задан, относительный
   * импорт, разрешающийся вне всех префиксов, — нарушение.
   */
  allowedPaths?: string[];
  /**
   * Закрытый префикс: спецификатор, равный `prefix` или начинающийся с
   * `prefix/`, обязан быть в `names` (имена входов пакета), иначе — нарушение.
   */
  entriesOnly?: { prefix: string; names: string[] };
};
