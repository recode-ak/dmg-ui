/** Зона проверки импортов: файлы по префиксу пути и спецификаторы, которые в них запрещены. */
export type ImportZone = {
  /** Префиксы путей файлов зоны. */
  include: string[];
  /** Суффиксы путей, исключённые из зоны (например `.test.ts`). */
  exclude: string[];
  /** Префиксы путей каталогов, вынесенных из зоны (у них своя зона со своим списком). */
  excludeDirs?: string[];
  /** Запрещённые спецификаторы: точные или с `*` на конце (префикс). */
  forbidden: string[];
  /** Белый список (формат как у `forbidden`): если задан, любой не относительный спецификатор вне списка — нарушение. */
  allowed?: string[];
  /** Префиксы путей от корня репо: относительный импорт, разрешающийся внутрь, — нарушение. */
  forbiddenPaths?: string[];
};
